rows = []
for l in open(os.path.join(HERE, 'lines.txt'), encoding='utf-8'):
    if not l.strip() or l.startswith('#'): continue
    clip, text, r, cat, gap = [x.strip() for x in l.split('|')]
    assert clip in CLIPS and r in ('ok', 'forced', 'none') and (cat in CATS or cat == '-'), l
    assert (gap == '-') == (r == 'ok') and (gap == '-' or gap in GAPS), l
    rows.append(dict(clip=clip, text=text, r=r, cat=cat, gap=gap))

n = len(rows); res = collections.Counter(x['r'] for x in rows)
cat_ok = collections.Counter(x['cat'] for x in rows if x['r'] == 'ok')
gaps = []
for g, (name, does, why) in GAPS.items():
    xs = [x for x in rows if x['gap'] == g]
    if not xs: continue
    gaps.append(dict(id=g, name=name, does=does, why=why, n=len(xs), clips=len({x['clip'] for x in xs}),
                     none=sum(x['r'] == 'none' for x in xs), forced=sum(x['r'] == 'forced' for x in xs),
                     near=collections.Counter(x['cat'] for x in xs if x['cat'] != '-').most_common(1)[0][0] if any(x['cat'] != '-' for x in xs) else '-',
                     lines=[dict(clip=x['clip'], text=x['text'], r=x['r'], cat=x['cat']) for x in xs]))
gaps.sort(key=lambda g: (-g['n'], -g['clips']))
per_clip = {c: dict(name=CLIPS[c], n=sum(x['clip'] == c for x in rows),
                    gap=sum(x['clip'] == c and x['r'] != 'ok' for x in rows)) for c in CLIPS}
stats = dict(lines=n, clips=len({x['clip'] for x in rows}), ok=res['ok'], forced=res['forced'], none=res['none'],
             cat_ok={c: cat_ok.get(c, 0) for c in CATS}, cat_names=CATS, gaps=gaps, per_clip=per_clip, rows=rows)
json.dump(stats, open(os.path.join(HERE, 'stats.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

